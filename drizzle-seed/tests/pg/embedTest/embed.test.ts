import { PGlite } from '@electric-sql/pglite';
import { eq, sql } from 'drizzle-orm';
import { type AnyPgColumn, embed, integer, pgTable, serial, text } from 'drizzle-orm/pg-core';
import { drizzle } from 'drizzle-orm/pglite';
import { expect, test } from 'vitest';
import { reset, seed } from '../../../src/index.ts';

const users = pgTable('users', {
	id: serial().primaryKey(),
	name: text().notNull(),
	address: embed({
		city: text().notNull(),
		zip: integer(),
		geo: embed({ lat: integer().notNull(), lng: integer() }),
	}),
});

const posts = pgTable('posts', {
	id: serial().primaryKey(),
	authorId: integer('author_id').notNull().references(() => users.id),
	meta: embed({ title: text().notNull(), views: integer() }),
});

const prepare = async () => {
	const db = drizzle({ client: new PGlite() });
	await db.execute(sql`
		create table users (
			id serial primary key,
			name text not null,
			address_city text not null,
			address_zip integer,
			address_geo_lat integer not null,
			address_geo_lng integer
		)
	`);
	await db.execute(sql`
		create table posts (
			id serial primary key,
			author_id integer not null references users (id),
			meta_title text not null,
			meta_views integer
		)
	`);
	return db;
};

test('seeds every column of an embed table, nested groups included', async () => {
	const db = await prepare();
	await seed(db, { users }, { count: 20 });

	const rows = await db.select().from(users);
	expect(rows.length).toBe(20);
	for (const row of rows) {
		expect(typeof row.address.city).toBe('string');
		expect(row.address.city.length).toBeGreaterThan(0);
		expect(typeof row.address.zip).toBe('number');
		expect(typeof row.address.geo.lat).toBe('number');
		expect(typeof row.address.geo.lng).toBe('number');
	}
});

test('refines embedded columns with nested keys', async () => {
	const db = await prepare();
	await seed(db, { users }, { count: 10 }).refine((funcs) => ({
		users: {
			columns: {
				address: {
					city: funcs.valuesFromArray({ values: ['Berlin', 'Paris'] }),
					zip: false,
					geo: { lat: funcs.intPrimaryKey() },
				},
			},
		},
	}));

	const rows = await db.select().from(users);
	expect(rows.length).toBe(10);
	for (const row of rows) {
		expect(['Berlin', 'Paris']).toContain(row.address.city);
		expect(row.address.zip).toBeNull();
	}
	expect(rows.map((row) => row.address.geo.lat).sort((a, b) => a! - b!)).toEqual(
		[...Array(10).keys()].map((i) => i + 1),
	);
	// not refined: still generated by default
	expect(rows.every((row) => typeof row.address.geo.lng === 'number')).toBe(true);
});

test('a relation to an embed table keeps its foreign key', async () => {
	const db = await prepare();
	await seed(db, { users, posts }, { count: 10 });

	const authors = await db.select().from(users);
	const rows = await db.select().from(posts);
	expect(rows.length).toBe(10);
	const ids = new Set(authors.map((author) => author.id));
	for (const row of rows) {
		expect(ids.has(row.authorId)).toBe(true);
		expect(typeof row.meta.title).toBe('string');
	}
});

test('refines an embed table that references another one, with `with`', async () => {
	const db = await prepare();
	await seed(db, { users, posts }, { count: 3 }).refine((funcs) => ({
		users: { with: { posts: 2 } },
		posts: { columns: { meta: { title: funcs.default({ defaultValue: 'hello' }) } } },
	}));

	expect(await db.select().from(posts).where(eq(posts.meta.title, 'hello'))).toHaveLength(6);
});

test('dryRun returns embedded values nested, as the table writes them', async () => {
	const db = await prepare();
	const data = await seed(db, { users }, { count: 3 }).dryRun();

	expect(data.users).toHaveLength(3);
	for (const row of data.users) {
		expect(typeof row.address.city).toBe('string');
		expect(typeof row.address.geo.lat).toBe('number');
		expect(Object.keys(row)).not.toContain('address.city');
	}
});

test('reset truncates embed tables', async () => {
	const db = await prepare();
	await seed(db, { users, posts }, { count: 5 });
	expect((await db.select().from(users)).length).toBe(5);

	await reset(db, { users, posts });
	expect(await db.select().from(users)).toEqual([]);
	expect(await db.select().from(posts)).toEqual([]);
});

test('a foreign key inside an embed group is filled from the table it references', async () => {
	const authors = pgTable('authors', { id: serial().primaryKey(), name: text().notNull() });
	const books = pgTable('books', {
		id: serial().primaryKey(),
		credits: embed({ authorId: integer().notNull().references(() => authors.id), role: text() }),
	});
	const db = drizzle({ client: new PGlite() });
	await db.execute(sql`create table authors (id serial primary key, name text not null)`);
	await db.execute(sql`
		create table books (
			id serial primary key,
			"credits_authorId" integer not null references authors (id),
			credits_role text
		)
	`);

	await seed(db, { authors, books }, { count: 10 });

	const ids = new Set((await db.select().from(authors)).map((author) => author.id));
	const rows = await db.select().from(books);
	expect(rows).toHaveLength(10);
	expect(rows.every((row) => ids.has(row.credits.authorId))).toBe(true);
});

test('seeds an embed table that is cyclic with another, through the update pass', async () => {
	const nodes = pgTable('nodes', {
		id: serial().primaryKey(),
		link: embed({ parentId: integer().references((): AnyPgColumn => nodes.id), label: text() }),
	});
	const db = drizzle({ client: new PGlite() });
	await db.execute(sql`
		create table nodes (
			id serial primary key,
			"link_parentId" integer references nodes (id),
			link_label text
		)
	`);

	await seed(db, { nodes }, { count: 10 });

	const rows = await db.select().from(nodes);
	expect(rows).toHaveLength(10);
	const ids = new Set(rows.map((row) => row.id));
	expect(rows.every((row) => row.link.parentId === null || ids.has(row.link.parentId))).toBe(true);
});

test('embedded columns keep their own names and prefixes', async () => {
	const accounts = pgTable('accounts', {
		id: serial().primaryKey(),
		billing: embed({ city: text(), country: text('bill_country') }, { prefix: 'b_' }),
		shipping: embed({ city: text('ship_city') }, { prefix: '' }),
	});
	const db = drizzle({ client: new PGlite() });
	await db.execute(sql`
		create table accounts (id serial primary key, b_city text, bill_country text, ship_city text)
	`);

	await seed(db, { accounts }, { count: 5 });

	const rows = await db.select().from(accounts);
	expect(rows).toHaveLength(5);
	expect(rows.every((row) => typeof row.billing.city === 'string' && typeof row.shipping.city === 'string')).toBe(
		true,
	);
});

test('embedded columns pick generators by their own name, not the name of the group', async () => {
	const contacts = pgTable('contacts', {
		id: serial().primaryKey(),
		email_prefs: embed({ locale: text().notNull(), email: text().notNull() }),
	});
	const db = drizzle({ client: new PGlite() });
	await db.execute(
		sql`create table contacts (id serial primary key, email_prefs_locale text not null, email_prefs_email text not null)`,
	);

	await seed(db, { contacts }, { count: 5 });

	const rows = await db.select().from(contacts);
	expect(rows.every((row) => row.email_prefs.email.includes('@'))).toBe(true);
	expect(rows.every((row) => !row.email_prefs.locale.includes('@'))).toBe(true);
});

test('a not null embedded column cannot be refined to false', async () => {
	const db = await prepare();
	await expect(
		seed(db, { users }, { count: 1 }).refine(() => ({ users: { columns: { address: { city: false } } } })),
	).rejects.toThrow("'address.city' column in the 'users' table");
});

test('unique generators work on embedded columns', async () => {
	const db = await prepare();
	await seed(db, { users }, { count: 30 }).refine((funcs) => ({
		users: { columns: { address: { zip: funcs.int({ minValue: 1, maxValue: 30, isUnique: true }) } } },
	}));

	expect(new Set((await db.select().from(users)).map((row) => row.address.zip)).size).toBe(30);
});

test('seeds with a fixed seed reproducibly', async () => {
	const first = await seed(await prepare(), { users }, { count: 5, seed: 7 }).dryRun();
	const second = await seed(await prepare(), { users }, { count: 5, seed: 7 }).dryRun();
	expect(first).toEqual(second);
});

test('dryRun renders sql with the embedded columns under their database names', async () => {
	const db = await prepare();
	const statements = await seed(db, { users }, { count: 2 }).dryRun({ output: 'sql' });

	expect(statements.join('\n')).toContain('"address_city", "address_zip", "address_geo_lat", "address_geo_lng"');
});

test('tables referencing each other through embed groups are seeded, the second pass included', async () => {
	const a = pgTable('a', {
		id: serial().primaryKey(),
		ref: embed({ bId: integer().references((): AnyPgColumn => b.id), tag: text() }),
	});
	const b = pgTable('b', {
		id: serial().primaryKey(),
		ref: embed({ aId: integer().notNull().references((): AnyPgColumn => a.id), tag: text() }),
	});
	const db = drizzle({ client: new PGlite() });
	await db.execute(sql`create table a (id serial primary key, "ref_bId" integer, ref_tag text)`);
	await db.execute(
		sql`create table b (id serial primary key, "ref_aId" integer not null references a (id), ref_tag text)`,
	);
	await db.execute(sql`alter table a add foreign key ("ref_bId") references b (id)`);

	const writes = [];
	for await (const write of seed(db, { a, b }, { count: 5 }).dryRun()) writes.push(write);
	expect(writes.some((write) => write.type === 'update' && write.tableName === 'a')).toBe(true);
	for (const write of writes) {
		if (write.type === 'update') expect(write.values).toHaveProperty('ref.bId');
	}

	await seed(db, { a, b }, { count: 5 });
	const rowsA = await db.select().from(a);
	const ids = new Set((await db.select().from(b)).map((row) => row.id));
	expect(rowsA).toHaveLength(5);
	expect(rowsA.every((row) => row.ref.bId !== null && ids.has(row.ref.bId))).toBe(true);
});
